// Perch bar: rows top to bottom use these palette letters. Left and right end columns are 'K' (outline).
// Wood knots 'S' are scattered at fixed positions so the bar looks hand made.
export function perchBar(width = META.perch.width) {
  const rowColors = 'KHTTSK';
  const knots = [[5,2],[6,2],[17,3],[24,2],[11,3],[33,3],[40,2],[47,2]];
  const grid = [];
  for (let y = 0; y < 6; y++) {
    let row = '';
    for (let x = 0; x < width; x++) row += (x === 0 || x === width - 1) ? 'K' : rowColors[y];
    grid.push(row.split(''));
  }
  for (const [x, y] of knots) if (x < width - 1) grid[y][x] = 'S';
  return grid.map(r => r.join(''));
}
